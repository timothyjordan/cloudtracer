#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_PROVIDERS_DIR = resolve(root, "providers");
export const DEFAULT_OUTPUT_PATH = resolve(root, "src/providers/generated.ts");

export function loadProviderDefinitions(providersDir = DEFAULT_PROVIDERS_DIR) {
  const files = readdirSync(providersDir)
    .filter((f) => f.endsWith(".json") && f !== "schema.json")
    .sort((a, b) => a.localeCompare(b));

  return files.map((file) => {
    const fullPath = resolve(providersDir, file);
    const data = JSON.parse(readFileSync(fullPath, "utf8"));
    return { file, data };
  });
}

export function renderGeneratedModule(entries) {
  const dns = [];
  const cdn = [];
  const hosting = [];
  const email = [];
  const thirdparty = [];
  const htmlFrameworks = [];
  const platformNames = [];
  const cdnEdgeNames = [];
  const directPlatformIps = [];
  const platformInfraRules = [];
  const dnsCrossRefRules = [];

  for (const { data } of entries) {
    const { id, name } = data;

    if (data.dns?.patterns?.length) {
      dns.push({ id, name, patterns: data.dns.patterns });
    }

    if (data.cdn) {
      const headers = data.cdn.headers ?? {};
      const cnames = data.cdn.cnames ?? [];
      if (Object.keys(headers).length > 0 || cnames.length > 0) {
        cdn.push({ id, name, headers, cnames });
      }
      if (data.cdn.is_platform && !platformNames.includes(name)) {
        platformNames.push(name);
      }
      if (data.cdn.is_cdn_edge && !cdnEdgeNames.includes(name)) {
        cdnEdgeNames.push(name);
      }
    }

    if (data.hosting) {
      if (data.hosting.asns?.length) {
        hosting.push({ id, name, asns: data.hosting.asns });
      }
      if (data.hosting.ips?.length) {
        directPlatformIps.push({ platform: name, ips: data.hosting.ips });
      }
      if (data.hosting.is_platform && !platformNames.includes(name)) {
        platformNames.push(name);
      }
      if (data.hosting.is_cdn_edge && !cdnEdgeNames.includes(name)) {
        cdnEdgeNames.push(name);
      }
    }

    if (data.email?.mx_patterns?.length) {
      email.push({ id, name, mx_patterns: data.email.mx_patterns });
    }

    if (data.thirdparty?.scripts?.length) {
      thirdparty.push({
        id,
        name,
        scripts: data.thirdparty.scripts,
        category: data.thirdparty.category,
      });
    }

    if (data.html_frameworks?.html_patterns?.length) {
      htmlFrameworks.push({
        id,
        name,
        html_patterns: data.html_frameworks.html_patterns,
        category: data.html_frameworks.category,
      });
    }

    if (Array.isArray(data.platform_rules)) {
      for (const rule of data.platform_rules) {
        if (rule.cdn) {
          platformInfraRules.push({
            platform: name,
            cdn: rule.cdn,
            ...(rule.ssl_issuer ? { sslIssuer: rule.ssl_issuer } : {}),
            ...(rule.ips?.length ? { ips: rule.ips } : {}),
          });
        }
        if (rule.dns_from) {
          dnsCrossRefRules.push({
            platform: name,
            dnsFrom: rule.dns_from,
          });
        }
      }
    }
  }

  return [
    "// Generated by scripts/build-providers.mjs from providers/*.json. Do not edit by hand.",
    "",
    "export interface DnsProviderEntry {",
    "  id: string;",
    "  name: string;",
    "  patterns: string[];",
    "}",
    "",
    "export interface CdnProviderEntry {",
    "  id: string;",
    "  name: string;",
    "  headers: Record<string, string>;",
    "  cnames: string[];",
    "}",
    "",
    "export interface HostingProviderEntry {",
    "  id: string;",
    "  name: string;",
    "  asns: number[];",
    "}",
    "",
    "export interface EmailProviderEntry {",
    "  id: string;",
    "  name: string;",
    "  mx_patterns: string[];",
    "}",
    "",
    "export interface ThirdPartyProviderEntry {",
    "  id: string;",
    "  name: string;",
    "  scripts: string[];",
    "  category: string;",
    "}",
    "",
    "export interface HtmlFrameworkProviderEntry {",
    "  id: string;",
    "  name: string;",
    "  html_patterns: string[];",
    "  category: string;",
    "}",
    "",
    "export interface DirectPlatformIpEntry {",
    "  platform: string;",
    "  ips: string[];",
    "}",
    "",
    "export interface PlatformInfraRuleEntry {",
    "  platform: string;",
    "  cdn: string;",
    "  sslIssuer?: string;",
    "  ips?: string[];",
    "}",
    "",
    "export interface DnsCrossRefRuleEntry {",
    "  platform: string;",
    "  dnsFrom: string;",
    "}",
    "",
    `export const DNS_PROVIDERS: readonly DnsProviderEntry[] = ${JSON.stringify(dns, null, 2)};`,
    "",
    `export const CDN_PROVIDERS: readonly CdnProviderEntry[] = ${JSON.stringify(cdn, null, 2)};`,
    "",
    `export const HOSTING_PROVIDERS: readonly HostingProviderEntry[] = ${JSON.stringify(hosting, null, 2)};`,
    "",
    `export const EMAIL_PROVIDERS: readonly EmailProviderEntry[] = ${JSON.stringify(email, null, 2)};`,
    "",
    `export const THIRDPARTY_PROVIDERS: readonly ThirdPartyProviderEntry[] = ${JSON.stringify(thirdparty, null, 2)};`,
    "",
    `export const HTML_FRAMEWORK_PROVIDERS: readonly HtmlFrameworkProviderEntry[] = ${JSON.stringify(htmlFrameworks, null, 2)};`,
    "",
    `export const PLATFORM_PROVIDER_NAMES: readonly string[] = ${JSON.stringify(platformNames, null, 2)};`,
    "",
    `export const CDN_EDGE_PROVIDER_NAMES: readonly string[] = ${JSON.stringify(cdnEdgeNames, null, 2)};`,
    "",
    `export const DIRECT_PLATFORM_IPS: readonly DirectPlatformIpEntry[] = ${JSON.stringify(directPlatformIps, null, 2)};`,
    "",
    `export const PLATFORM_INFRA_RULES: readonly PlatformInfraRuleEntry[] = ${JSON.stringify(platformInfraRules, null, 2)};`,
    "",
    `export const DNS_CROSS_REF_RULES: readonly DnsCrossRefRuleEntry[] = ${JSON.stringify(dnsCrossRefRules, null, 2)};`,
    "",
  ].join("\n");
}

export function buildProviders({
  providersDir = DEFAULT_PROVIDERS_DIR,
  outputPath = DEFAULT_OUTPUT_PATH,
  check = false,
} = {}) {
  const entries = loadProviderDefinitions(providersDir);
  const rendered = renderGeneratedModule(entries);

  if (check) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
    return {
      ok: current === rendered,
      count: entries.length,
    };
  }

  writeFileSync(outputPath, rendered, "utf8");
  return { ok: true, count: entries.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const result = buildProviders({ check });
  if (check) {
    if (!result.ok) {
      console.error(
        "src/providers/generated.ts is out of date with providers/*.json. Run `npm run providers:build`.",
      );
      process.exit(1);
    }
    console.log(`src/providers/generated.ts is up to date (${result.count} providers).`);
  } else {
    console.log(`Built src/providers/generated.ts from ${result.count} providers.`);
  }
}
